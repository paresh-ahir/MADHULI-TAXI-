export function relatedRoutes(slug, limit = 4) {
  const current = getRoute(slug);
  if (!current) return routes.slice(0, limit);
  return routes.filter((item) => item.slug !== slug && (item.from === current.from || item.to === current.to)).slice(0, limit);
}
